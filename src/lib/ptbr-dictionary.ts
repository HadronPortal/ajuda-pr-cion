const DICTIONARY = new Map<string, string>();
for (const [wrong, right] of Object.entries({ ...RAW_MAP, ...TYPO_MAP })) {
  if (wrong !== right && !wrong.includes("_")) DICTIONARY.set(wrong, right);
}

