function matchCase(source: string, target: string) {
  if (source === source.toUpperCase() && source.length > 1) return target.toUpperCase();
  if (source[0] === source[0]?.toUpperCase()) {
    return target[0].toUpperCase() + target.slice(1);
  }
  return target;
}

/**
 * Corrige uma única palavra usando o dicionário local.
 * Retorna `null` quando não há correção conhecida (ou quando a palavra é
 * protegida: sigla, código, nome próprio, palavra com número/acento).
 */
export function correctWord(word: string): string | null {
  if (!word || word.length < 2 || word.length > 30) return null;
  if (/[\d@/\\_.:#-]/.test(word)) return null; // códigos, protocolos, e-mails
  const lower = word.toLowerCase();
  if (PROTECTED.has(lower)) return null;
  // Sigla em caixa alta com 2+ letras (ex.: PRC, NFE) — nunca corrigir.
  if (word.length > 1 && word === word.toUpperCase() && /^\p{L}+$/u.test(word)) return null;
  const fixed = DICTIONARY.get(lower);
  if (!fixed || fixed === lower) return null;
  return matchCase(word, fixed);
}

